/**
 * Declarative definitions for AMCMS records. The server derives validation, column allow-lists,
 * search, filters and audit behaviour from these; the admin UI derives tables and forms.
 */

export type FieldType =
  | "text"
  | "textarea"
  | "email"
  | "tel"
  | "number"
  | "integer"
  | "money"
  | "date"
  | "datetime"
  | "select"
  | "boolean"
  | "ref";

export type RefTarget = ResourceKey | "staff";

export interface FieldDef {
  name: string;
  label: string;
  type: FieldType;
  required?: boolean;
  max?: number;
  min?: number;
  options?: readonly Option[];
  ref?: RefTarget;
  /** show as a table column */
  list?: boolean;
  /** included in free-text search (text-like columns only) */
  searchable?: boolean;
  /** offered as a table filter (select/ref/boolean) */
  filter?: boolean;
  /** server-managed; never accepted from clients */
  readonly?: boolean;
  /** editable on create only */
  createOnly?: boolean;
  help?: string;
  pattern?: string;
  patternMessage?: string;
  uppercase?: boolean;
  /** masked in audit logs and CSV exports */
  sensitive?: boolean;
  default?: string | number | boolean;
  /** form layout */
  wide?: boolean;
}

export interface ResourceDef {
  key: ResourceKey;
  table: string;
  label: string;
  singular: string;
  read: Permission;
  write: Permission;
  export?: Permission;
  titleField: string;
  subtitleField?: string;
  fields: readonly FieldDef[];
  defaultSort: { column: string; ascending: boolean };
  /** soft-delete via archived_at instead of DELETE */
  archivable?: boolean;
  /** hard delete allowed (child/config records) */
  deletable?: boolean;
  /** creation allowed through the generic engine */
  creatable?: boolean;
  createdByColumn?: string;
  /** extra read-only columns returned to the client */
  extraSelect?: readonly string[];
}

